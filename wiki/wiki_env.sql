------------------------------------------------------------------------------
-- wiki_env - what web_wiki needs from the application around it.
--
-- web_wiki was written inside a larger application, which supplied who is
-- signed in, how much they may do, people's names and an email routine. Here
-- those are one small package over a table of users, so the wiki runs on its
-- own. A real installation replaces the bodies below with its own sign-in and
-- mail; nothing in web_wiki changes.
--
--   current_user      who is signed in (a cookie here; your SSO or session)
--   security_level    0 none, 1 read, 2 edit, 5 administer
--   contact_name      "Last, First" for a user id
--   send_mail         email a page (kept in WIKI_OUTBOX here, not sent)
--   date_value        a posted date field as a DATE (database forms)
--   page_head         anything your application adds to every page head
--   allowed           the gateway's request validation function
--   sign_in/sign_out  the demo's user picker
------------------------------------------------------------------------------

create table wiki_users
(
    userid     varchar2(10) not null
   ,last_name  varchar2(40)
   ,first_name varchar2(40)
   ,seclevel   number default 1 not null
   ,active     varchar2(1) default '1' not null
   ,constraint wiki_users_pk primary key (userid)
);

comment on table wiki_users is 'People who may use the wiki, and how much each may do (1 read, 2 edit, 5 administer)';

insert into wiki_users values ('ADMIN',  'Admin',  'Ada',    5, '1');
insert into wiki_users values ('EDITOR', 'Editor', 'Ed',     2, '1');
insert into wiki_users values ('READER', 'Reader', 'Rita',   1, '1');
insert into wiki_users values ('PAT',    'Jones',  'Pat',    2, '1');

-- Mail the wiki would have sent. A real installation sends it instead.
create table wiki_outbox
(
    id        number generated by default on null as identity
   ,sent      date default sysdate not null
   ,mail_from varchar2(10)
   ,mail_to   varchar2(10)
   ,subject   varchar2(200)
   ,body      clob
   ,constraint wiki_outbox_pk primary key (id)
);

create or replace package wiki_env is

  function current_user return varchar2;
  function security_level(p_user in varchar2) return number;
  function contact_name(p_user in varchar2) return varchar2;
  procedure send_mail(p_from in varchar2, p_to in varchar2, p_subject in varchar2, p_body in varchar2);
  function date_value(p in varchar2) return date;
  procedure page_head;
  function allowed(p_procedure in varchar2) return boolean;

  -- the demo's user picker: /wiki/wiki_env.sign_in
  procedure sign_in(p_user in varchar2 default null);
  procedure outbox;

end wiki_env;
/

create or replace package body wiki_env is

  c_cookie constant varchar2(30) := 'wiki_user';
  c_home   constant varchar2(60) := 'web_wiki.show_wiki';

  -- Whoever the cookie names, if they are an active user. Without one the demo
  -- signs you in as EDITOR, so the wiki can be tried straight away.
  function current_user return varchar2 is
    l_c    owa_cookie.cookie;
    l_user varchar2(30);
    l_n    number;
  begin
    begin
      l_c := owa_cookie.get(c_cookie);
      if l_c.num_vals > 0 then
        l_user := upper(substr(l_c.vals(1), 1, 10));
      end if;
    exception
      when others then l_user := null;
    end;
    if l_user is null then
      return 'EDITOR';
    end if;
    select count(*) into l_n from wiki_users where userid = l_user and active = '1';
    return case when l_n > 0 then l_user end;
  end;

  function security_level(p_user in varchar2) return number is
    l_level number;
  begin
    select seclevel into l_level from wiki_users where userid = p_user and active = '1';
    return l_level;
  exception
    when no_data_found then return 0;
  end;

  function contact_name(p_user in varchar2) return varchar2 is
    l_name varchar2(100);
  begin
    select last_name || ', ' || first_name into l_name from wiki_users where userid = p_user;
    return l_name;
  exception
    when no_data_found then return p_user;
  end;

  procedure send_mail(p_from in varchar2, p_to in varchar2, p_subject in varchar2, p_body in varchar2) is
  begin
    insert into wiki_outbox (mail_from, mail_to, subject, body)
    values (p_from, p_to, substr(p_subject, 1, 200), p_body);
  end;

  -- a date field as the browser posts it (YYYY-MM-DD), or the US form
  function date_value(p in varchar2) return date is
  begin
    if p is null then
      return null;
    elsif regexp_like(p, '^\d{4}-\d{2}-\d{2}') then
      return to_date(substr(p, 1, 10), 'YYYY-MM-DD');
    else
      return to_date(p, 'MM/DD/YYYY');
    end if;
  end;

  procedure page_head is
  begin
    null;      -- e.g. your application's own validation script for page forms (valforms)
  end;

  -- Only these may be called through the gateway (web_wiki.set_batch_user is not one).
  function allowed(p_procedure in varchar2) return boolean is
    l varchar2(200) := lower(p_procedure);
  begin
    return l in ('web_wiki.show_wiki', 'web_wiki.show_wiki_data', '!web_wiki.saveformdata',
                 'web_wiki.saveformdata', 'web_wiki.delete_wiki', 'web_wiki.rename_wiki',
                 'web_wiki.purge_wiki', 'web_wiki.email_form', 'web_wiki.email_wiki',
                 'web_wiki.wiki_js', 'web_wiki.export_page', 'web_wiki.export_data',
                 'wiki_env.sign_in', 'wiki_env.outbox');
  end;

  procedure sign_in(p_user in varchar2 default null) is
    l_user varchar2(30) := upper(substr(p_user, 1, 10));
    l_n    number := 0;
  begin
    if l_user is not null then
      select count(*) into l_n from wiki_users where userid = l_user and active = '1';
    end if;
    if l_n > 0 then
      owa_util.mime_header('text/html', false);
      owa_cookie.send(c_cookie, l_user, null, owa_util.get_owa_service_path);
      owa_util.redirect_url(owa_util.get_owa_service_path || c_home, false);
      owa_util.http_header_close;
      return;
    end if;
    htp.p('<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">'
       || '<meta name="viewport" content="width=device-width, initial-scale=1"><title>Wiki: sign in</title>'
       || '<style>body{font:10pt verdana,sans-serif;margin:24px}td,th{padding:4px 10px;text-align:left}</style></head><body>');
    htp.p('<h2>Sign in to the wiki</h2><p>A demo: pick who you are. Each person has a security level, '
       || 'which decides what the wiki lets them do.</p><table><tr><th>User</th><th>Name</th><th>Can</th></tr>');
    for r in (select userid, first_name || ' ' || last_name nm, seclevel from wiki_users where active = '1' order by seclevel desc, userid) loop
      htp.p('<tr><td><a href="wiki_env.sign_in?p_user=' || r.userid || '">' || r.userid || '</a></td><td>'
         || htf.escape_sc(r.nm) || '</td><td>'
         || case when r.seclevel >= 5 then 'read, edit, edit locked pages, purge'
                 when r.seclevel >= 2 then 'read and edit'
                 else 'read only' end || '</td></tr>');
    end loop;
    htp.p('</table><p><a href="' || c_home || '">Back to the wiki</a> &middot; '
       || '<a href="wiki_env.outbox">Mail the wiki has sent</a></p></body></html>');
  end;

  procedure outbox is
  begin
    htp.p('<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Wiki: outbox</title>'
       || '<style>body{font:10pt verdana,sans-serif;margin:24px}td,th{padding:4px 10px;text-align:left;vertical-align:top;border-bottom:1px solid #ddd}</style></head><body>');
    htp.p('<h2>Mail the wiki has sent</h2><p>The demo keeps email here instead of sending it.</p>'
       || '<table><tr><th>Sent</th><th>From</th><th>To</th><th>Subject</th></tr>');
    for r in (select sent, mail_from, mail_to, subject from wiki_outbox order by id desc) loop
      htp.p('<tr><td>' || to_char(r.sent, 'MM/DD/YY HH24:MI') || '</td><td>' || htf.escape_sc(r.mail_from)
         || '</td><td>' || htf.escape_sc(r.mail_to) || '</td><td>' || htf.escape_sc(r.subject) || '</td></tr>');
    end loop;
    htp.p('</table><p><a href="' || c_home || '">Back to the wiki</a></p></body></html>');
  end;

end wiki_env;
/
