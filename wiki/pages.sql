-- The table the "Equipment loans" database form writes to, and the line that
-- lets wiki forms write to it at all.
create table wiki_loans
(
    loan_id   number generated by default on null as identity
   ,borrower  varchar2(60) not null
   ,item      varchar2(60) not null
   ,due_date  date
   ,notes     varchar2(400)
   ,constraint wiki_loans_pk primary key (loan_id)
);

insert into ddg_wiki_form_tables (table_name, pk_column, min_seclevel) values ('WIKI_LOANS', 'LOAN_ID', 2);

